def load_progress():
    try:
        with open(PROGRESS_FILE, "r", encoding="utf-8") as fh:
            data = json.load(fh)
        base = dict(DEFAULT_PROGRESS)
        base.update({k: v for k, v in data.items() if k in base})
        return base
    except Exception:
        return dict(DEFAULT_PROGRESS)


def rotated(lst, k):
    k %= len(lst)
    return lst[k:] + lst[:k]

